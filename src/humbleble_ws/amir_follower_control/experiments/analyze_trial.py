"""Analyze separate experiment receipts; GT never enters the follower."""
import argparse
import json
from pathlib import Path

import numpy as np
from amir_follower_control.core import ArmURDF


def seconds(stamp):
    return stamp['sec']+stamp['nanosec']*1e-9


def pose_matrix(transform):
    q=transform['rotation']
    x,y,z,w=np.array([q[k] for k in ('x','y','z','w')],dtype=float)
    if abs(x*x+y*y+z*z+w*w-1)>1e-3:
        raise ValueError('invalid evaluation orientation')
    matrix=np.eye(4)
    matrix[:3,:3]=[[1-2*(y*y+z*z),2*(x*y-z*w),2*(x*z+y*w)],
                   [2*(x*y+z*w),1-2*(x*x+z*z),2*(y*z-x*w)],
                   [2*(x*z-y*w),2*(y*z+x*w),1-2*(x*x+y*y)]]
    matrix[:3,3]=[transform['translation'][k] for k in ('x','y','z')]
    return matrix


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('directory')
    args=parser.parse_args()
    root=Path(args.directory)
    trial=json.loads((root/'summary.json').read_text())
    records=[]
    for line in (root/'evaluation.jsonl').open():
        row=json.loads(line)
        if row['stage']=='excitation' and row['sim_time']<=trial.get('end_sim_time',float('inf')):
            records.append(row)
    commands={round(seconds(r['message']['header']['stamp']),6)
              for r in records if r['topic']=='follower_arm_command'}
    first_seen={}
    tracking=[]
    state_times=[]
    poses={}
    # The descriptor sits beside the trial directory, generated by the scene.
    arm_files={robot:root.parent/f'{robot}.urdf' for robot in ('amir1','amir2')}
    arms={robot:ArmURDF(path.read_text()) for robot,path in arm_files.items() if path.is_file()}
    joints={}
    grasp_coordinates={robot:[] for robot in arms}
    first_leader_command=None
    first_leader_encoder=None
    grasps={robot:[] for robot in ('amir1','amir2')}
    base_commands=[]
    for row in records:
        msg=row['message']
        if row['topic']=='follower_base_command':
            base_commands.append([msg[part][axis] for part in ('linear','angular') for axis in ('x','y','z')])
        if (row['topic']=='leader_command' and first_leader_command is None and
                any(abs(msg[part][axis])>1e-12 for part in ('linear','angular') for axis in ('x','y','z'))):
            first_leader_command=row['sim_time']
        if (row['topic']=='/amir1/mecanum_drive_controller/odometry' and first_leader_encoder is None and
                abs(msg['twist']['twist']['linear']['x'])>1e-5):
            first_leader_encoder=seconds(msg['header']['stamp'])
        if row['topic']=='follower_arm_state':
            timestamp=seconds(msg['header']['stamp'])
            reference=msg.get('reference',msg.get('desired'))
            key=round(timestamp-seconds(reference['time_from_start']),6)
            if key in commands:
                first_seen.setdefault(key,timestamp-key)
            tracking.append(msg['error']['positions'])
            state_times.append(timestamp)
        elif row['topic']=='world_GT':
            current={t['child_frame_id']:pose_matrix(t['transform']) for t in msg['transforms']}
            for transform in msg['transforms']:
                poses.setdefault(transform['child_frame_id'],[]).append(transform['transform'])
            if 'cooperative_payload' in current:
                inverse=np.linalg.inv(current['cooperative_payload'])
                for robot,arm in arms.items():
                    if robot in current and robot in joints:
                        g=arm.evaluate(joints[robot])[0]
                        grasp_coordinates[robot].append((inverse@current[robot]@g)[:3,3])
        for robot in grasps:
            if row['topic']==f'/{robot}/joint_states' and robot in arms:
                mapping=dict(zip(msg['name'],msg['position']))
                joints[robot]=[mapping[name] for name in arms[robot].names]
            if row['topic']==f'/{robot}/grasp/state':
                grasps[robot].append(msg['data'])
    result={'trial':trial,'arm_commands':len(commands),
            'commands_observable_in_controller_state':len(first_seen),
            'state_reflection_note':'First published state reflecting a command; superseded commands may be unobservable. This is not an isolated hardware latency measurement.',
            'GT_note':'Evaluation-process receipt times; source transform stamps are zero.',
            'slip_note':'TCP coordinates in payload, from evaluation GT and latest received local joints; this includes contact slip and geometry deformation, not a direct pad-slip sensor.',
            'grasp_states':{key:sorted(set(value)) for key,value in grasps.items()},
            'GT_translation_delta_m':{}}
    if trial.get('stimulus')=='leader':
        result['first_nonzero_leader_command_sim_time']=first_leader_command
        result['first_leader_encoder_vx_over_10um_s_time']=first_leader_encoder
        result['first_follower_arm_command_stamp']=min(commands) if commands else None
        if commands and first_leader_encoder is not None:
            result['leader_encoder_to_first_follower_command_s']=min(commands)-first_leader_encoder
    if first_seen:
        result['command_first_state_delay_min_median_p99_max_s']=np.quantile(
            list(first_seen.values()),[0,.5,.99,1]).tolist()
    result['base_command_axis_units']=['m/s','m/s','m/s','rad/s','rad/s','rad/s']
    result['base_command_samples']=len(base_commands)
    result['base_command_peak_abs_xyz_rpy']=np.max(np.abs(base_commands),axis=0).tolist() if base_commands else None
    if len(state_times)>1:
        result['controller_state_period_median_s']=float(np.median(np.diff(state_times)))
    if tracking:
        result['controller_reference_feedback_peak_error_rad']=np.max(np.abs(tracking),axis=0).tolist()
    for model,samples in poses.items():
        xyz=np.array([[sample['translation'][axis] for axis in ('x','y','z')] for sample in samples])
        result['GT_translation_delta_m'][model]=(xyz[-1]-xyz[0]).tolist()
    result['TCP_relative_payload']={}
    for robot,samples in grasp_coordinates.items():
        if samples:
            positions=np.array(samples)
            result['TCP_relative_payload'][robot]={
                'initial_m':positions[0].tolist(),
                'delta_m':(positions[-1]-positions[0]).tolist(),
                'peak_displacement_m':float(np.max(np.linalg.norm(positions-positions[0],axis=1)))}
    (root/'evaluation_metrics.json').write_text(json.dumps(result,indent=2,allow_nan=False))
    print(json.dumps(result,indent=2))


if __name__=='__main__':
    main()
